def copy_descriptor(i, j, type_counts=(3, 3), width=10):
    copies = sum(type_counts)
    stop = copies * width
    if i < stop and j < stop:
        first, second = i // width, j // width
        first_type, second_type = int(first >= type_counts[0]), int(second >= type_counts[0])
        if first == second:
            return ("same_copy", first_type, i % width, j % width)
        return ("different_copy", first_type, second_type, i % width, j % width)
    if i < stop:
        return ("to_filler", int(i // width >= type_counts[0]), i % width)
    if j < stop:
        return ("from_filler", int(j // width >= type_counts[0]), j % width)
    return ("filler_diagonal" if i == j else "filler_off_diagonal",)


def variable_groups(type_counts=(3, 3), fillers=2, width=10):
    size = sum(type_counts) * width + fillers
    groups = {}
    for i in range(size):
        for j in range(size):
            groups.setdefault(copy_descriptor(i, j, type_counts, width), []).append((i, j))
    return list(groups), list(groups.values())


def complete_binary_solution_space(columns, target):
    pivots, kernel = {}, []
    for index, column in enumerate(columns):
        value, combination = column, 1 << index
        while value:
            pivot = value.bit_length() - 1
            if pivot not in pivots:
                pivots[pivot] = (value, combination)
                break
            old, used = pivots[pivot]
            value ^= old
            combination ^= used
        if not value:
            kernel.append(combination)
    value, particular = target, 0
    while value:
        pivot = value.bit_length() - 1
        if pivot not in pivots:
            return None, kernel, {"rank": len(pivots), "augmented_rank": len(pivots) + 1,
                                  "nullity": len(kernel), "nonzero_reduced_target_bit": pivot}
        old, used = pivots[pivot]
        value ^= old
        particular ^= used
    # Every kernel vector was generated by one new independent domain
    # coordinate, so these form the complete kernel, not sampled moves.
    for word in kernel:
        result = 0
        for i in range(len(columns)):
            if (word >> i) & 1:
                result ^= columns[i]
        if result:
            raise ValueError("a computed affine-kernel direction does not annihilate the exact Gram map")
    if len(pivots) + len(kernel) != len(columns):
        raise ValueError("the affine-kernel dimension failed rank-nullity")
    return particular, kernel, {"rank": len(pivots), "augmented_rank": len(pivots), "nullity": len(kernel)}


def representative_data(order, phase):
    small, boundary = template(), boundary_data(order, phase)
    width, copies, fillers = 10, 6, 2
    s, t = copies * width + fillers, len(boundary["border_C"])
    correction = np.zeros((s, s), dtype=np.int64)
    w = np.zeros_like(correction)
    for index in range(copies):
        part = slice(width * index, width * (index + 1))
        correction[part, part] = small["T"]
        w[part, part] = small["W"]
    correction[-fillers:, -fillers:] = np.eye(fillers, dtype=np.int64)
    c = 1 ^ correction
    active = np.concatenate([small["a"]] * copies + [np.zeros(fillers, dtype=np.int64)])
    a = active[:, None] * boundary["boundary_vector"][None, :]
    ones, zeros = np.ones((s, s), dtype=np.int64), np.zeros((s, s), dtype=np.int64)
    y0, y1 = ones ^ (3 * c), (ones ^ (3 * c)) * w
    u0, u1 = np.ones_like(a) ^ (3 * a), 2 * a
    d0 = np.ones((t, t), dtype=np.int64) ^ (3 * boundary["border_C"])
    h0 = np.block([[ones, y0, u0], [y0, ones, u0], [u0.T, u0.T, d0]])
    h1 = np.block([[zeros, y1, u1], [y1, zeros, u1], [u1.T, u1.T, np.zeros((t, t), dtype=np.int64)]])
    fixed_h2 = np.zeros_like(h0)
    fixed_h2[-t:, -t:] = MULTIPLY[d0, boundary["border_next_bits"]]
    if not np.array_equal(product(h0, CONJUGATE[h0].T), np.eye(len(h0), dtype=np.int64)):
        raise ValueError("the labelled representative zeroth Gram failed")
    if np.any(derivative(h0, h1)):
        raise ValueError("the labelled representative first Gram failed")
    return {"s": s, "t": t, "C": c, "W": w, "A": a, "H0": h0, "H1": h1,
            "fixed_H2": fixed_h2, "border_second_bits": boundary["border_next_bits"]}


def roots_from_assignment(data, names, groups, assignment):
    s, t, h0 = data["s"], data["t"], data["H0"]
    x2, y2 = np.zeros((s, s), dtype=np.int64), np.zeros((s, s), dtype=np.int64)
    count = len(names)
    for index, positions in enumerate(groups):
        for i, j in positions:
            x2[i, j] = (assignment >> index) & 1
            y2[i, j] = (assignment >> (index + count)) & 1
    zeros = np.zeros((s, s), dtype=np.int64)
    first = np.block([[zeros, data["W"], data["A"]], [data["W"], zeros, data["A"]],
                      [data["A"].T, data["A"].T, np.zeros((t, t), dtype=np.int64)]])
    second = np.block([[x2, y2, np.zeros((s, t), dtype=np.int64)],
                       [y2, x2, np.zeros((s, t), dtype=np.int64)],
                       [np.zeros((t, s), dtype=np.int64), np.zeros((t, s), dtype=np.int64), data["border_second_bits"]]])
    return (h0 == 2).astype(np.int64), first + 2 * second


def four_difference_witness(exponents):
    for i in range(len(exponents)):
        for j in range(i):
            differences = (exponents[i] - exponents[j]) % 4
            if len(np.unique(differences)) == 4:
                columns = [int(np.flatnonzero(differences == residue)[0]) for residue in range(4)]
                return {"rows": [i, j], "columns": columns,
                        "dyadic_differences_mod4": [int(differences[k]) for k in columns],
                        "rules_out_every_row_column_gauge_into_two_adjacent_channels": True}
    return None


def labelled_model(order, phase):
    data = representative_data(order, phase)
    h0, h1, s = data["H0"], data["H1"], data["s"]
    fixed = product(h1, CONJUGATE[h1].T) ^ product(h0, CONJUGATE[h1].T)
    target = encode_blocks(fixed ^ derivative(h0, data["fixed_H2"]),
                           fixed ^ derivative(h1, data["fixed_H2"]))
    names, groups = variable_groups()
    columns = []
    for core in ("X", "Y"):
        for positions in groups:
            positions = ([(i, j) for i, j in positions] + [(s + i, s + j) for i, j in positions]
                         if core == "X" else
                         [(i, s + j) for i, j in positions] + [(s + i, j) for i, j in positions])
            second = [(i, j, int(h0[i, j])) for i, j in positions]
            third = [(i, j, int(h1[i, j])) for i, j in positions]
            columns.append(encode_blocks(sparse_derivative(h0, second),
                                         sparse_derivative(h0, third) ^ sparse_derivative(h1, second)))
    solution, kernel, rank = complete_binary_solution_space(columns, target)
    digest = hashlib.sha256()
    byte_width = (4 * len(h0) ** 2 + 7) // 8
    for vector in [*columns, target]:
        digest.update(vector.to_bytes(byte_width, "little"))
    report = {"source_order": order, "phase": phase,
              "actual_type_copy_counts": [31, 31] if order == 1499 else [31, 93],
              "actual_inactive_fillers": 128 if order == 1499 else 256,
              "representative_type_copy_counts": [3, 3], "representative_inactive_fillers": 2,
              "representative_source_order": len(h0), "number_second_bit_variables": len(columns),
              "variable_descriptors_per_core": [list(name) for name in names],
              "exact_binary_system": rank, "binary_system_sha256": digest.hexdigest(),
              "full_affine_kernel_basis_nonzero_variable_indices":
              [[i for i in range(len(columns)) if (word >> i) & 1] for word in kernel],
              "status": "SOLVED" if solution is not None else "INCONSISTENT_IN_THIS_LABELLED_SLICE",
              "scope": "Two labelled copy types with independent same-copy, different-copy and filler phase bits."}
    if solution is None:
        return report
    colors, exponents = roots_from_assignment(data, names, groups, solution)
    grams = polynomial_gram_from_roots(colors, exponents)
    if not np.array_equal(grams[0], np.eye(len(h0), dtype=np.int64)) or any(np.any(g) for g in grams[1:]):
        raise ValueError("the labelled model's particular solution failed independent root-Gram replay")
    report.update({"particular_solution_nonzero_variable_indices":
                   [i for i in range(len(columns)) if (solution >> i) & 1],
                   "all_four_representative_root_Gram_coefficients_verified": True,
                   "particular_solution_four_difference_witness": four_difference_witness(exponents)})
    if not kernel:
        expected = int(order == 2999)
        if solution != (((1 << len(columns)) - 1) if expected else 0):
            raise ValueError("the unique labelled solution changed from the old constant slice")
        gauge = np.array([-1] * (2 * s) + [1] * data["t"]) if expected else np.zeros(len(h0), dtype=np.int64)
        gauged = (exponents + gauge[:, None] + gauge[None, :]) % 4
        if not np.all((gauged == 0) | (gauged == 1)):
            raise ValueError("the explicit adjacent-channel gauge does not apply to the unique solution")
        report.update({"unique_solution_is_previous_constant_second_bits": expected,
                       "entire_affine_space_has_explicit_adjacent_channel_gauge": True,
                       "row_and_column_gauge_core": -1 if expected else 0,
                       "row_and_column_gauge_border": 1 if expected else 0,
                       "remaining_dyadic_channels_mod4": [0, 1],
                       "no_new_anti_collapse_candidate_in_this_labelled_slice": True})
    else:
        report["affine_kernel_requires_anti_collapse_analysis"] = True
    return report


def certificate():
    return {"schema": "labelled-copy-second-ramification-v1",
            "coefficient_ring": "F4[pi]/(pi^4)",
            "all_copy_type_counts_and_filler_counts_preserve_actual_parities": True,
            "three_representatives_per_type_cover_same_and_different_copy_row_pair_cases": True,
            "routes": [labelled_model(order, phase) for order, phase in ((1499, 96), (2999, 48), (2999, 96))],
            "native_probe_run": False, "higher_bit_solving_performed": False,
            "new_large_residue_or_characteristic_zero_source_claimed": False}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--output", type=Path)
    action.add_argument("--check", type=Path)
    args = parser.parse_args()
    report = certificate()
    if args.check:
        if json.loads(args.check.read_text()) != report:
            raise ValueError("the labelled-copy certificate failed replay")
    else:
        args.output.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({"routes": [[route["source_order"], route["phase"], route["exact_binary_system"]]
                                 for route in report["routes"]], "native_probe_run": False}))


if __name__ == "__main__":
    main()
