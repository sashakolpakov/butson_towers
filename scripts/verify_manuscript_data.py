assert len(A) == len(B) == 13
assert all(len(h) == 13 for h in A+B)
def dot(x, y):
    return sum(a*b for a, b in zip(x, y))
for i in range(13):
    for j in range(13):
        assert dot(A[i], B[j]) == dot(B[i], A[j])
        assert dot(A[i], A[j]) + 3*dot(B[i], B[j]) == 52*(i == j)

